#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const docsRoot = path.join(repoRoot, 'docs');
const outputPath = path.join(docsRoot, 'data', 'app-assets.js');

const roots = [
  'app/sprites',
  'audio/sfx',
  'audio/music',
  'audio/episodes',
  'video/episodes',
  'data',
  'app/display-schema.js',
  'app/display-name-utils.js',
  'layout-builder/canonical-test-layout.js'
];

const EXT_MIME = {
  '.gif': 'image/gif',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.js': 'text/javascript',
  '.json': 'application/json',
  '.mp3': 'audio/mpeg',
  '.mp4': 'video/mp4',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.webp': 'image/webp'
};

function toPosix(value) {
  return value.split(path.sep).join('/');
}

function walk(target, files = []) {
  if (!fs.existsSync(target)) return files;
  const stat = fs.statSync(target);
  if (stat.isFile()) {
    files.push(target);
    return files;
  }
  for (const child of fs.readdirSync(target).sort()) {
    walk(path.join(target, child), files);
  }
  return files;
}

function assetKind(relativePath) {
  if (relativePath.startsWith('app/sprites/')) return 'sprite';
  if (relativePath.startsWith('audio/sfx/')) return 'sfx';
  if (relativePath.startsWith('audio/music/')) return 'music';
  if (relativePath.startsWith('audio/episodes/')) return relativePath.endsWith('.json') ? 'audio-manifest' : 'narration-audio';
  if (relativePath.startsWith('video/episodes/')) return 'video';
  if (relativePath.startsWith('data/')) return 'data';
  if (relativePath.startsWith('app/')) return 'runtime';
  if (relativePath.startsWith('layout-builder/')) return 'runtime';
  return 'asset';
}

function assetId(relativePath) {
  return relativePath
    .replace(/\.[a-z0-9]+$/i, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '.')
    .replace(/^\.+|\.+$/g, '');
}

function titleFromPath(relativePath) {
  const name = path.basename(relativePath, path.extname(relativePath));
  return name
    .replace(/[_-]+/g, ' ')
    .replace(/\b\w/g, letter => letter.toUpperCase());
}

const sourceFiles = roots.flatMap(root => walk(path.join(docsRoot, root)))
  .filter(file => path.resolve(file) !== outputPath)
  .map(file => {
    const relativePath = toPosix(path.relative(docsRoot, file));
    const ext = path.extname(file).toLowerCase();
    const stat = fs.statSync(file);
    return {
      id: assetId(relativePath),
      label: titleFromPath(relativePath),
      kind: assetKind(relativePath),
      path: relativePath,
      mimeType: EXT_MIME[ext] || 'application/octet-stream',
      sizeBytes: stat.size
    };
  });

const idCounts = sourceFiles.reduce((counts, file) => {
  counts[file.id] = (counts[file.id] || 0) + 1;
  return counts;
}, {});

const files = sourceFiles.map(file => {
  if (idCounts[file.id] <= 1) return file;
  const ext = path.extname(file.path).toLowerCase().replace(/^\./, '');
  return { ...file, id: ext ? `${file.id}.${ext}` : file.id };
}).sort((a, b) => a.kind.localeCompare(b.kind) || a.path.localeCompare(b.path));

const output = `// Generated by scripts/generate-app-asset-manifest.js. Do not edit by hand.\n(function () {\n  window.FOODRANKED_APP_ASSETS = ${JSON.stringify(files, null, 2)};\n})();\n`;

fs.writeFileSync(outputPath, output);
console.log(`Wrote ${toPosix(path.relative(repoRoot, outputPath))} with ${files.length} assets.`);
